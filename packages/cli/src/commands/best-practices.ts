  // 7. Decision Best Practices
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Decision Best Practices');
  lines.push('');
  lines.push('1. **Meaningful outcome labels** — Never use generic labels like "Outcome 1" or "True". Use labels that describe the business condition (e.g., "Account Is Active", "High Priority Case"). "Yes" / "No" are acceptable for simple binary decisions.');
  lines.push('2. **Always include a default outcome with a descriptive label** — Every decision must have a `default` path that handles the "else" case, even if it leads nowhere. The default label must also be descriptive (e.g., "No Matching Account Found", "Normal or Low Priority") — never use just "Default".');
  lines.push('3. **Use the right null-check operator for the data type:**');
  lines.push('   - Records (SObject variables, lookup results): `isNotNull` / `isNull`');
  lines.push('   - Strings/text fields: `isNotBlank` / `isBlank` (handles both null and empty string)');
  lines.push('   - Collections: `isNotEmpty` / `isEmpty`');
  lines.push('4. **Keep decisions focused** — Each decision should test one logical concept. Avoid cramming unrelated conditions into a single decision.');
  lines.push('');
  lines.push('Example of a well-structured decision:');
  lines.push('```yaml');
  lines.push('  - decision: Route_By_Priority');
  lines.push('    label: Route Case by Priority');
  lines.push('    description: Routes the case to the appropriate handling path based on its priority level.');
  lines.push('    rules:');
  lines.push('      - name: Is_Critical');
  lines.push('        label: Critical Priority');
  lines.push('        when:');
  lines.push('          - $Record.Priority == "Critical"');
  lines.push('        next: Handle_Critical');
  lines.push('      - name: Is_High');
  lines.push('        label: High Priority');
  lines.push('        when:');
  lines.push('          - $Record.Priority == "High"');
  lines.push('        next: Handle_High');
  lines.push('    default:');
  lines.push('      label: Normal or Low Priority');
  lines.push('      next: Handle_Standard');
  lines.push('```');
  lines.push('');

  // ----------------------------------------------------------
  // 7b. Designing for Multi-Scenario Record Triggers
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Designing for Multi-Scenario Record Triggers');
  lines.push('');
  lines.push('A single record-triggered flow that handles **N independent scenarios** against the');
  lines.push('same (or closely-related) collection is a common shape in ops-heavy orgs — e.g., one');
  lines.push('Account-after-save flow that, depending on trigger flags, sends a welcome email,');
  lines.push('stamps a stage date, notifies a success manager, and opens a task. The instinctive');
  lines.push('shape — one decision branch per flag, each branch running its own loop — produces N');
  lines.push('parallel loops over the same collection and N copies of every guard (email-bounce');
  lines.push('check, permission check, null check). That is the **loop-multiplication anti-pattern**.');
  lines.push('');
  lines.push('### Scenario Dispatch: One Loop, Chained Decisions');
  lines.push('');
  lines.push('The canonical shape: one query → one loop → one chain of in-loop decisions that each');
  lines.push('gate a scenario-specific action. Guards that apply to every scenario live once, at');
  lines.push('the top of the loop body.');
  lines.push('');
  lines.push('```yaml');
  lines.push('# BAD -- DO NOT DO THIS: one loop per scenario (loop multiplication)');
  lines.push('# Every new scenario adds a Filter + Loop + Guard + Action = 4 nodes.');
  lines.push('steps:');
  lines.push('  - filter: Filter_For_Welcome');
  lines.push('    collection: Get_Contacts');
  lines.push('    where: [SendWelcome__c == true]');
  lines.push('  - loop: Loop_Welcome');
  lines.push('    collection: Filter_For_Welcome');
  lines.push('    iterationNext: Guard_Welcome_Bounce');
  lines.push('    afterLastNext: Filter_For_Stage');
  lines.push('  - decision: Guard_Welcome_Bounce');
  lines.push('    rules:');
  lines.push('      - name: OK');
  lines.push('        when: [Loop_Welcome.Contact.IsEmailBounced == false]');
  lines.push('        next: Send_Welcome');
  lines.push('    default: { next: Loop_Welcome }');
  lines.push('  - action: Send_Welcome');
  lines.push('    actionType: emailSimple');
  lines.push('    next: Loop_Welcome');
  lines.push('  # ...repeat Filter + Loop + Guard + Action for Stage, Notify, Task...');
  lines.push('```');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT: one loop, chained decisions inside the body');
  lines.push('# Every new scenario adds a Decision + Action = 2 nodes. Guards live once.');
  lines.push('steps:');
  lines.push('  - loop: Loop_Contacts');
  lines.push('    collection: Get_Contacts');
  lines.push('    iterationNext: Guard_Email_Bounce');
  lines.push('    afterLastNext: Done');
  lines.push('  - decision: Guard_Email_Bounce');
  lines.push('    label: Shared Guard — Skip Bounced Contacts');
  lines.push('    rules:');
  lines.push('      - name: Email_Deliverable');
  lines.push('        when: [Loop_Contacts.Contact.IsEmailBounced == false]');
  lines.push('        next: Dispatch_Welcome');
  lines.push('    default: { label: "Bounced — Skip", next: Loop_Contacts }');
  lines.push('  - decision: Dispatch_Welcome');
  lines.push('    rules:');
  lines.push('      - name: Needs_Welcome');
  lines.push('        when: [Loop_Contacts.SendWelcome__c == true]');
  lines.push('        next: Send_Welcome');
  lines.push('    default: { next: Dispatch_Stage }');
  lines.push('  - action: Send_Welcome');
  lines.push('    actionType: emailSimple');
  lines.push('    next: Dispatch_Stage');
  lines.push('  - decision: Dispatch_Stage');
  lines.push('    rules:');
  lines.push('      - name: Needs_Stage_Stamp');
  lines.push('        when: [Loop_Contacts.StampStage__c == true]');
  lines.push('        next: Stamp_Stage');
  lines.push('    default: { next: Loop_Contacts }');
  lines.push('  - assignment: Stamp_Stage');
  lines.push('    operations: [Loop_Contacts.Stage_Date__c = $Flow.CurrentDateTime]');
  lines.push('    next: Loop_Contacts');
  lines.push('```');
  lines.push('');
  lines.push('Design heuristics:');
  lines.push('');
  lines.push('- **One loop per shared collection.** If two loops iterate the same collection (or a');
  lines.push('  filtered subset of it), collapse them.');
  lines.push('- **Guards live once.** A condition that applies to every scenario (email bounce,');
  lines.push('  permission check, record-type filter) belongs at the top of the loop body, not');
  lines.push('  duplicated per branch.');
  lines.push('- **Dispatch with decisions, not filters.** Per-scenario filters multiply nodes; a');
  lines.push('  per-iteration decision is free at runtime.');
  lines.push('- **Cost-of-new-scenario test.** Count the nodes needed to add one more scenario. In a');
  lines.push('  well-factored dispatch flow the answer is **2** (decision + action). If it is **4 or');
  lines.push('  more** (filter + loop + guard + action), duplication is baked in — refactor.');
  lines.push('');
  lines.push('### When Scenario Dispatch Does NOT Apply');
  lines.push('');
  lines.push('Keep scenarios separate when:');
  lines.push('');
  lines.push('- The scenarios operate on **different objects** or **materially different collections**.');
  lines.push('- One scenario needs bulk DML on the full collection and another needs per-record work');
  lines.push('  on a small subset — forcing both through one loop turns a bulk DML into an in-loop');
  lines.push('  one.');
  lines.push('- The iteration **order or partitioning** differs (e.g., one scenario processes only');
  lines.push('  primaries, another processes secondaries in a different order).');
  lines.push('');

  // ----------------------------------------------------------
  // 8. Anti-Patterns with Corrections
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Common Anti-Patterns and Corrections');
  lines.push('');
  lines.push('### Anti-Pattern: Loop Multiplication (N Loops Over The Same Collection)');
  lines.push('');
  lines.push('If you find yourself writing two or more loops over the same (or closely-related');
  lines.push('sub-) collection — each with its own email-bounce guard, permission check, or null');
  lines.push('check — collapse them into one loop with a chain of decisions inside the body. One');
  lines.push('shared guard instead of N; one loop variable instead of N; adding a new scenario');
  lines.push('costs 2 nodes (decision + action) instead of 4 (filter + loop + guard + action).');
  lines.push('See **Designing for Multi-Scenario Record Triggers** above for the canonical');
  lines.push('before/after example and the cost-of-new-scenario test.');
  lines.push('');
  lines.push('### Anti-Pattern: Query Inside a Loop');
  lines.push('');
  lines.push('```yaml');
  lines.push('# BAD -- DO NOT DO THIS: lookup inside a loop');
  lines.push('steps:');
  lines.push('  - loop: Loop_Accounts');
  lines.push('    label: Loop Over Accounts');
  lines.push('    collection: varCol_Accounts');
  lines.push('    iterationNext: Get_Contacts_For_Account');
  lines.push('    afterLastNext: Done');
  lines.push('  - lookup: Get_Contacts_For_Account');
  lines.push('    label: Get Contacts for This Account');
  lines.push('    object: Contact');
  lines.push('    where:');
  lines.push('      - AccountId == Loop_Accounts.Id');
  lines.push('    next: Loop_Accounts');
  lines.push('```');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT: Query all contacts once before the loop');
  lines.push('steps:');
  lines.push('  - lookup: Get_All_Related_Contacts');
  lines.push('    label: Get All Related Contacts');
  lines.push('    object: Contact');
  lines.push('    where:');
  lines.push('      - AccountId in varCol_AccountIds');
  lines.push('    next: Loop_Accounts');
  lines.push('  - loop: Loop_Accounts');
  lines.push('    label: Loop Over Accounts');
  lines.push('    collection: varCol_Accounts');
  lines.push('    iterationNext: Process_Account');
  lines.push('    afterLastNext: Done');
  lines.push('```');
  lines.push('');
  lines.push('### Anti-Pattern: Multiple DML for the Same Object');
  lines.push('');
  lines.push('```yaml');
  lines.push('# BAD -- DO NOT DO THIS: two separate updates on the same object');
  lines.push('steps:');
  lines.push('  - recordUpdate: Update_Status');
  lines.push('    label: Update Account Status');
  lines.push('    object: Account');
  lines.push('    where:');
  lines.push('      - Id == $Record.Id');
  lines.push('    fields:');
  lines.push('      Status__c: "Active"');
  lines.push('    next: Update_Description');
  lines.push('  - recordUpdate: Update_Description');
  lines.push('    label: Update Account Description');
  lines.push('    object: Account');
  lines.push('    where:');
  lines.push('      - Id == $Record.Id');
  lines.push('    fields:');
  lines.push('      Description: "Updated by Flow"');
  lines.push('```');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT: Consolidate into a single update');
  lines.push('steps:');
  lines.push('  - recordUpdate: Update_Account');
  lines.push('    label: Update Account Status and Description');
  lines.push('    object: Account');
  lines.push('    where:');
  lines.push('      - Id == $Record.Id');
  lines.push('    fields:');
  lines.push('      Status__c: "Active"');
  lines.push('      Description: "Updated by Flow"');
  lines.push('```');
  lines.push('');
  lines.push('### Anti-Pattern: Missing Null Check After Lookup');
  lines.push('');
  lines.push('```yaml');
  lines.push('# BAD -- DO NOT DO THIS: using lookup result without null check');
  lines.push('steps:');
  lines.push('  - lookup: Get_Account');
  lines.push('    label: Get Account');
  lines.push('    object: Account');
  lines.push('    getFirst: true');
  lines.push('    where:');
  lines.push('      - Id == $Record.AccountId');
  lines.push('    next: Use_Account_Data');
  lines.push('  - assignment: Use_Account_Data');
  lines.push('    label: Use Account Data');
  lines.push('    operations:');
  lines.push('      - varTxt_AccountName = Get_Account.Name');
  lines.push('```');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT: Check for null before using the result');
  lines.push('steps:');
  lines.push('  - lookup: Get_Account');
  lines.push('    label: Get Account');
  lines.push('    object: Account');
  lines.push('    getFirst: true');
  lines.push('    where:');
  lines.push('      - Id == $Record.AccountId');
  lines.push('    next: Check_Account_Exists');
  lines.push('  - decision: Check_Account_Exists');
  lines.push('    label: Was Account Found?');
  lines.push('    rules:');
  lines.push('      - name: Account_Found');
  lines.push('        label: Account Found');
  lines.push('        when:');
  lines.push('          - Get_Account isNotNull');
  lines.push('        next: Use_Account_Data');
  lines.push('    default:');
  lines.push('      label: Account Not Found');
  lines.push('      next: Handle_Error');
  lines.push('  - assignment: Use_Account_Data');
  lines.push('    label: Use Account Data');
  lines.push('    operations:');
  lines.push('      - varTxt_AccountName = Get_Account.Name');
  lines.push('```');
  lines.push('');

  // ----------------------------------------------------------
  // 9. Error Handling
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Error Handling');
  lines.push('');
  lines.push('### Fault Paths for DML Operations');
  lines.push('');
  lines.push('DML operations (recordCreate, recordUpdate, recordDelete) can fail due to validation');
  lines.push('rules, trigger errors, or data issues. Use the `faultNext` property to handle errors');
  lines.push('gracefully instead of letting the flow crash silently.');
  lines.push('');
  lines.push('```yaml');
  lines.push('steps:');
  lines.push('  - recordUpdate: Update_Account');
  lines.push('    label: Update Account Record');
  lines.push('    inputReference: varCol_AccountsToUpdate');
  lines.push('    faultNext: Handle_Update_Error');
  lines.push('    next: Success_Screen');
  lines.push('  - screen: Handle_Update_Error');
  lines.push('    label: Update Failed');
  lines.push('    fields:');
  lines.push('      - display: Error_Message');
  lines.push('        value: "An error occurred while updating the account. Please try again or contact your administrator."');
  lines.push('```');
  lines.push('');
  lines.push('### Input Validation in Screen Flows');
  lines.push('');
  lines.push('Validate user input on screen fields before processing. Use the `required` property');
  lines.push('and `validation` rules to catch bad data early.');
  lines.push('');
  lines.push('```yaml');
  lines.push('  - screen: Input_Screen');
  lines.push('    label: Enter Contact Details');
  lines.push('    fields:');
  lines.push('      - input: Email_Address');
  lines.push('        dataType: String');
  lines.push('        label: Email Address');
  lines.push('        required: true');
  lines.push('        validation:');
  lines.push('          formula: \'CONTAINS({!Email_Address}, "@")\'');
  lines.push('          errorMessage: "<p>Please enter a valid email address.</p>"');
  lines.push('      - input: Phone_Number');
  lines.push('        dataType: String');
  lines.push('        label: Phone Number');
  lines.push('        required: true');
  lines.push('        validation:');
  lines.push('          formula: \'LEN({!Phone_Number}) >= 10\'');
  lines.push('          errorMessage: "<p>Phone number must be at least 10 digits.</p>"');
  lines.push('      - component: Parent_Email');
  lines.push('        extensionName: flowruntime:email');
  lines.push('        inputs:');
  lines.push('          label: Parent Email');
  lines.push('          value: $Record.Parent_Email__c');
  lines.push('        validation:');
  lines.push('          formula: \'LOWER({!Parent_Email.value}) <> LOWER({!Email_Address})\'');
  lines.push('          errorMessage: "<p>Parent email must differ from participant email.</p>"');
  lines.push('```');
  lines.push('');
  lines.push('`validation` is supported on every interactive screen field type — `input`, `dropdown`, `multiselect`, `radio`, `textarea`, `checkbox`, `toggle`, and `component` — so you can attach cross-field rules directly to LWC component instances like `flowruntime:email` or `flowruntime:phone`.');
  lines.push('');

  // ----------------------------------------------------------
  // 10. $Record Usage in Record-Triggered Flows
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## $Record: Don\'t Re-Query the Trigger Object');
  lines.push('');
  lines.push('In record-triggered flows, `$Record` already contains the triggering record.');
  lines.push('Querying the same object by `$Record.Id` wastes a SOQL query.');
  lines.push('');
  lines.push('```yaml');
  lines.push('# BAD -- wastes a SOQL query');
  lines.push('steps:');
  lines.push('  - lookup: Get_Account');
  lines.push('    object: Account');
  lines.push('    where:');
  lines.push('      - Id == $Record.Id');
  lines.push('```');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT -- use $Record directly');
  lines.push('steps:');
  lines.push('  - assignment: Set_Values');
  lines.push('    operations:');
  lines.push('      - varTxt_AccountName = $Record.Name');
  lines.push('```');
  lines.push('');

  // ----------------------------------------------------------
  // 11. Query Optimization
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Query Optimization');
  lines.push('');
  lines.push('### storeOutputAutomatically: when to use it, when to avoid it');
  lines.push('');
  lines.push('`storeOutputAutomatically: true` retrieves **all** fields on the queried record.');
  lines.push('Prefer explicit `fields:` — it avoids unnecessary data retrieval and limits data-leak');
  lines.push('risk in screen flows exposed to external users.');
  lines.push('');
  lines.push('**`fields:` and `storeOutputAutomatically: true` are mutually exclusive.** Salesforce');
  lines.push('rejects the combination at deploy time. Pick one.');
  lines.push('');
  lines.push('**Legitimate exception — dotted *relationship* paths.** `<queriedFields>` (the XML');
  lines.push('produced from `fields:`) accepts flat field names only, and `outputs:` cannot bind');
  lines.push('dotted paths either. If you need to read a field on a *related* object (e.g.,');
  lines.push('`Contact.Email` or `Contact.IsEmailBounced` from an `AccountContactRelation`');
  lines.push('lookup), `storeOutputAutomatically: true` is the only option. Document the reason');
  lines.push('in the lookup\'s `description` so reviewers (and the linter) know it is intentional.');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT: storeOutputAutomatically required to read related-object fields');
  lines.push('steps:');
  lines.push('  - lookup: Get_Account_Contact_Relations');
  lines.push('    label: Get ACRs With Contact Fields');
  lines.push('    description: >-');
  lines.push('      Uses storeOutputAutomatically because downstream logic reads Contact.Email');
  lines.push('      and Contact.IsEmailBounced. Flat fields: cannot express dotted paths.');
  lines.push('    object: AccountContactRelation');
  lines.push('    storeOutputAutomatically: true');
  lines.push('    where:');
  lines.push('      - AccountId == $Record.AccountId');
  lines.push('```');
  lines.push('');
  lines.push('The `store-output-auto` lint rule downgrades its warning to informational when the');
  lines.push('lookup carries a `description`, so documenting the reason also quiets the linter.');
  lines.push('');
  lines.push('### Same-object field access with explicit fields — use `outputs:`');
  lines.push('');
  lines.push('When you only need flat fields on the queried object itself, prefer explicit');
  lines.push('`fields:` plus an `outputs:` mapping. **Do not** assume that downstream');
  lines.push('`LookupName.FieldName` references will work — they do not when `fields:` is used.');
  lines.push('Salesforce sets `storeOutputAutomatically=false` whenever explicit fields are');
  lines.push('present, and dot-notation against the lookup name is rejected at deploy time:');
  lines.push('');
  lines.push('> When the StoreOutputAutomatically field is set to "False", the X.Y reference');
  lines.push('> isn\'t supported.');
  lines.push('');
  lines.push('The `outputs:` block on a lookup binds each queried field to a variable. Reference');
  lines.push('the variable instead of dot-notation:');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT: explicit fields + outputs mapping + variable references');
  lines.push('variables:');
  lines.push('  varTxt_InverseId:');
  lines.push('    dataType: String');
  lines.push('');
  lines.push('steps:');
  lines.push('  - lookup: Get_Party_Role');
  lines.push('    object: PartyRoleRelation');
  lines.push('    getFirst: true');
  lines.push('    fields: [Id, RelatedInverseRecordId]');
  lines.push('    outputs:');
  lines.push('      RelatedInverseRecordId: varTxt_InverseId');
  lines.push('    where:');
  lines.push('      - Id == $Record.PartyRoleRelationId');
  lines.push('    next: Has_Inverse');
  lines.push('  - decision: Has_Inverse');
  lines.push('    rules:');
  lines.push('      - name: Yes_Inverse');
  lines.push('        # Reference the bound variable, NOT Get_Party_Role.RelatedInverseRecordId');
  lines.push('        when:');
  lines.push('          - varTxt_InverseId isNotNull');
  lines.push('        next: Create_Inverse');
  lines.push('    default:');
  lines.push('      label: No Inverse');
  lines.push('```');
  lines.push('');
  lines.push('The `lookup-fields-blocks-dotref` lint rule catches the inverse mistake — explicit');
  lines.push('fields plus a downstream `LookupName.Field` reference — before `flowml check` hits');
  lines.push('the org.');
  lines.push('');
  lines.push('### Use getFirst: true for Single Records');
  lines.push('');
  lines.push('When expecting a single record from a lookup, always set `getFirst: true`.');
  lines.push('This improves performance and simplifies downstream null checks (single record vs collection).');
  lines.push('');
  lines.push('### Collection Filter Pattern');
  lines.push('');
  lines.push('Instead of querying N times inside a loop, query once and filter in memory:');
  lines.push('');
  lines.push('```yaml');
  lines.push('# CORRECT: Query once, filter in memory');
  lines.push('steps:');
  lines.push('  - lookup: Get_All_Contacts');
  lines.push('    object: Contact');
  lines.push('    where:');
  lines.push('      - AccountId in varCol_AccountIds');
  lines.push('    next: Filter_By_Status');
  lines.push('  - filter: Filter_By_Status');
  lines.push('    collection: Get_All_Contacts');
  lines.push('    where:');
  lines.push('      - Status__c == "Active"');
  lines.push('```');
  lines.push('');

  // ----------------------------------------------------------
  // 12. Entry Criteria & Recursive Prevention
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Entry Criteria & Recursive Prevention');
  lines.push('');
  lines.push('### Always Use Entry Criteria');
  lines.push('');
  lines.push('Record-triggered flows without entry criteria run on **every save**. Always add');
  lines.push('`entryConditions` and consider `requiresRecordChangedToMeetCriteria: true`:');
  lines.push('');
  lines.push('```yaml');
  lines.push('trigger:');
  lines.push('  type: RecordAfterSave');
  lines.push('  object: Account');
  lines.push('  recordTriggerType: Update');
  lines.push('  requiresRecordChangedToMeetCriteria: true');
  lines.push('  entryConditions:');
  lines.push('    - Status__c isChanged');
  lines.push('  next: Process_Change');
  lines.push('```');
  lines.push('');
  lines.push('### Recursive After-Update Prevention');
  lines.push('');
  lines.push('**CRITICAL**: An after-save flow that updates the same object that triggered it');
  lines.push('can cause an **infinite loop**. Always add entry conditions with `isChanged` on');
  lines.push('the specific fields that trigger the flow, ensuring the update doesn\'t re-trigger it.');
  lines.push('');

  // ----------------------------------------------------------
  // 13. Before-Save vs After-Save
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Before-Save vs After-Save');
  lines.push('');
  lines.push('| Aspect | Before-Save | After-Save |');
  lines.push('|---|---|---|');
  lines.push('| Modifies | Trigger record only (`$Record`) | Related/child records, external systems |');
  lines.push('| DML cost | **Zero** — modifies record in memory | Requires explicit DML operations |');
  lines.push('| Has record ID | No (record not yet saved) | Yes (record committed) |');
  lines.push('| Callouts | Not allowed | Allowed |');
  lines.push('| Emails | Not allowed | Allowed |');
  lines.push('| Use for | Field defaults, validation, same-record updates | Related records, notifications, integrations |');
  lines.push('');

  // ----------------------------------------------------------
  // 14. Transform vs Loop Decision
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Transform vs Loop Decision Criteria');
  lines.push('');
  lines.push('| Use Case | Use Transform (30-50% faster) | Use Loop |');
  lines.push('|---|---|---|');
  lines.push('| Map fields between types | Yes | No |');
  lines.push('| Bulk field assignments | Yes | No |');
  lines.push('| Per-record IF/ELSE decisions | No | Yes |');
  lines.push('| Counters, flags, state tracking | No | Yes |');
  lines.push('| Simple formula calculations | Yes | No |');
  lines.push('| Varying business rules per record | No | Yes |');
  lines.push('');

  // ----------------------------------------------------------
  // 15. Three-Tier Error Handling
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Three-Tier Error Handling');
  lines.push('');
  lines.push('1. **Input Validation** — Validate data before DML: null checks, format checks, business rules.');
  lines.push('2. **DML Fault Handling** — Add `faultNext` on every DML operation. Capture `$Flow.FaultMessage`.');
  lines.push('3. **Rollback** — Use `recordRollback` to undo pending changes when a multi-step transaction fails.');
  lines.push('');

  // ----------------------------------------------------------
  // 16. Screen Flow Transaction Boundaries
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Screen Flow Transaction Boundaries');
  lines.push('');
  lines.push('**In screen flows, each screen commits the prior transaction.** DML before a screen');
  lines.push('element cannot be rolled back after the screen. Design accordingly:');
  lines.push('');
  lines.push('1. Collect ALL input across screens first (store in flow variables)');
  lines.push('2. Perform ALL DML operations after the final screen');
  lines.push('3. Use `recordRollback` for multi-step forms that need atomicity');
  lines.push('');

  // ----------------------------------------------------------
  // 17. Hardcoded IDs and URLs
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Avoid Hardcoded IDs and URLs');
  lines.push('');
  lines.push('Salesforce record IDs (15/18 character) are **org-specific**. Hardcoding them causes');
  lines.push('deployment failures between sandboxes. Similarly, hardcoded URLs break across environments.');
  lines.push('');
  lines.push('Instead, use:');
  lines.push('- **Custom Labels** — for user-facing text and simple config values');
  lines.push('- **Custom Metadata Types** — for thresholds, feature flags, queue names');
  lines.push('- **Query results** — look up records by DeveloperName, not by ID');
  lines.push('');

  // ----------------------------------------------------------
  // 18. Custom Metadata for Business Logic
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Custom Metadata for Business Logic');
  lines.push('');
  lines.push('Store frequently changing business values in Custom Metadata Types (CMDT) instead');
  lines.push('of hardcoding. CMDT records are metadata (deployable) and accessible in formulas');
  lines.push('via `$CustomMetadata.Type__mdt.Record.Field__c` at zero SOQL cost.');
  lines.push('');
  lines.push('Good candidates: discount thresholds, SLA hours, feature toggles, email recipients,');
  lines.push('queue/user DeveloperNames. Never store Salesforce IDs in CMDT.');
  lines.push('');

  // ----------------------------------------------------------
  // 19. Flow Activation & Bypass
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Flow Activation & Bypass');
  lines.push('');
  lines.push('### Deploy as Draft First');
  lines.push('');
  lines.push('Always deploy flows with `status: Draft`. Test in sandbox, then activate.');
  lines.push('Never activate untested flows in production.');
  lines.push('');
  lines.push('### Bypass Mechanism for Data Loads');
  lines.push('');
  lines.push('For bulk data imports, implement a bypass using Custom Permissions:');
  lines.push('');
  lines.push('```yaml');
  lines.push('trigger:');
  lines.push('  type: RecordAfterSave');
  lines.push('  object: Account');
  lines.push('  entryConditions:');
  lines.push('    logic: "1 AND 2"');
  lines.push('    conditions:');
  lines.push('      1: Status__c isChanged');
  lines.push('      2: $Permission.Bypass_Flow__c == false');
  lines.push('  next: Process_Change');
  lines.push('```');
  lines.push('');

  // ----------------------------------------------------------
  // 20. Properties to Omit
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Properties to Omit When Generating FlowML');
  lines.push('');
  lines.push('When generating new FlowML, do NOT include these internal properties:');
  lines.push('');
  lines.push('| Property | Reason |');
  lines.push('|---|---|');
  lines.push('| `_xmlOrder` | Internal round-trip ordering — auto-managed |');
  lines.push('| `processMetadata` | Boilerplate Canvas settings — auto-set by Salesforce |');
  lines.push('| `extraProperties` | Internal property bag — auto-managed |');
  lines.push('| `locationX` / `locationY` | Canvas coordinates — preserved on round-trip; omit when authoring new flows (Salesforce auto-positions on deploy) |');
  lines.push('');
  lines.push('The `name` property in `flow:` supports only letters, numbers, and underscores (no spaces).');
  lines.push('The `label` property supports spaces and special characters.');
  lines.push('');

  // ----------------------------------------------------------
  // 21. Quick Reference Checklist
  // ----------------------------------------------------------
  lines.push('---');
  lines.push('');
  lines.push('## Quick Reference Checklist');
  lines.push('');
  lines.push('### Formatting');
  lines.push('- No empty lines in YAML output');
  lines.push('- 2-space indentation throughout');
  lines.push('- Descriptive `label` on every element');
  lines.push('- `description` on `flow:` block and complex steps');
  lines.push('');
  lines.push('### Naming');
  lines.push('- Flow API names: `Object_TriggerType_Purpose`');
  lines.push('- Resources: `[type][dataType]_PascalCaseName` (e.g., `varTxt_StatusMessage`, `forBool_IsEligible`)');
  lines.push('- Step API names: PascalCase with underscores (e.g., `Get_Active_Accounts`)');
  lines.push('- All element names must be unique across the flow (steps, resources, scheduled paths share one namespace); decision rule names must be unique within their decision');
  lines.push('');
  lines.push('### Performance');
  lines.push('- NEVER put DML (recordCreate/recordUpdate/recordDelete) inside loops');
  lines.push('- NEVER put queries (lookup) inside loops');
  lines.push('- Use before-save triggers for same-record field updates');
  lines.push('- Consolidate DML: one operation per object');
  lines.push('- Avoid nested loops');
  lines.push('- Use `inputReference: collectionVar` for bulk DML on collections');
  lines.push('');
  lines.push('### Element Usage');
  lines.push('- Use loops + collections for repetitive operations (never duplicate steps)');
  lines.push('- Use `filter` steps to reduce collections');
  lines.push('- Use `transform` steps to sort collections');
  lines.push('- Use subflows for reusable logic');
  lines.push('');
  lines.push('### Safety');
  lines.push('- Null-check after every lookup (decision with `isNotNull` for records)');
  lines.push('- Check collection size before DML (decision with `isNotEmpty`)');
  lines.push('- Use correct null-check operator: `isNotNull` for records, `isNotBlank` for strings, `isNotEmpty` for collections');
  lines.push('- Add `faultNext` on DML operations for error handling');
  lines.push('- Validate screen inputs with `required` and `validation` rules');
  lines.push('');
  lines.push('### Decision Rules');
  lines.push('- Meaningful outcome labels on ALL outcomes including default (never "Outcome 1" or just "Default")');
  lines.push('- Always include a `default` outcome with a descriptive label');
  lines.push('');
  lines.push('### Flow Structure');
  lines.push('- Use `trigger:` for record-triggered/scheduled flows, `start:` for screen/subflows — never both');
  lines.push('- Include `interviewLabel` on production flows for debugging');
  lines.push('- Set `runInMode` explicitly on triggered flows and document the choice');
  lines.push('- Always add `entryConditions` on record-triggered flows');
  lines.push('- Use `requiresRecordChangedToMeetCriteria: true` to prevent unnecessary runs');
  lines.push('- **Node-budget heuristic.** Record-triggered or auto-launched flows crossing ~25 top-level nodes are candidates for consolidation; above ~40 they are almost certainly under-factored. Look for multiple loops over the same collection, duplicated guard decisions, or redundant filter steps — see *Designing for Multi-Scenario Record Triggers*. (Screen-flow wizards legitimately run longer; this heuristic targets backend flows.)');
  lines.push('- **Cost-of-new-scenario test.** In a well-factored dispatch flow, adding one scenario costs 2 nodes (decision + action). If it costs 4+ (filter + loop + guard + action), duplication is baked in — refactor to one shared loop.');
  lines.push('');
  lines.push('### Variables & References');
  lines.push('- Define `isInput`/`isOutput` on variables for subflows and screen flow parameters');
  lines.push('- Use `{!varName}` in formulas and text templates, bare refs in conditions/assignments');
  lines.push('- Use `$Record.Field` directly — don\'t re-query the trigger object');
  lines.push('');
  lines.push('### Avoid');
  lines.push('- Hardcoded Salesforce IDs (org-specific, cause deployment failures)');
  lines.push('- `storeOutputAutomatically: true` on lookups (data leak + perf risk)');
  lines.push('- DML between screens in screen flows (back button causes data issues)');
  lines.push('- After-save flows that update the trigger object without entry conditions (infinite loop)');
  lines.push('- `$GlobalConstant.True`, `$GlobalConstant.False`, `$GlobalConstant.EmptyString` — these are Salesforce UI labels, not valid XML. Use `true`, `false`, and `""` instead');
  lines.push('- Omit `_xmlOrder`, `processMetadata`, `extraProperties`, `locationX`/`locationY` when generating new flows');
  lines.push('- Use `customError:` for before-save validation (not `raw:`)');
  lines.push('');

  return lines.join('\n');
